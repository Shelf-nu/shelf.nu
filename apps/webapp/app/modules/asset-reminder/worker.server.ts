/**
 * Marks a failure of the recurring-reminder advance step. Like every handler
 * failure it reaches pg-boss, which retries the job (recurring jobs are sent
 * with a wider retry budget, see `recurringReminderJobOptions`). The advance
 * step runs BEFORE any notification is sent, so a retry caused by it cannot
 * double-email.
 */
export class RecurringAdvanceError extends Error {
  constructor(cause: unknown, reminderId: string) {
    super(`Failed to advance recurring reminder ${reminderId}`);
    this.name = "RecurringAdvanceError";
    this.cause = cause;
  }
}

const ASSET_REMINDER_INCLUDES_FOR_EMAIL = {
  teamMembers: {
    select: {
      user: {
        select: {
          email: true,
          firstName: true,
          lastName: true,
          displayName: true,
        },
      },
    },
  },
  asset: {
    select: {
      id: true,
      title: true,
      mainImage: true,
      mainImageExpiration: true,
      archivedAt: true,
    },
  },
  organization: { select: { name: true, customEmailFooter: true } },
} satisfies Prisma.AssetReminderInclude;

type UserToEmail = Pick<
  User,
  "email" | "firstName" | "lastName" | "displayName"
> & {
  isOwner?: boolean;
};

const ASSET_SCHEDULER_EVENT_HANDLERS: Record<
  AssetsEventType,
  (job: PgBoss.Job<AssetsSchedulerData>) => Promise<void>
> = {
  REMINDER: async (job) => {
    const reminder = await db.assetReminder.findFirst({
      // eslint-disable-next-line local-rules/require-org-scope-on-id-queries -- idor-safe: background pg-boss job handler, no request/tenant context; reminderId is system-generated by the scheduler queue, not attacker-supplied
      where: { id: job.data.reminderId },
      include: ASSET_REMINDER_INCLUDES_FOR_EMAIL,
    });

    if (!reminder) {
      Logger.warn(
        new ShelfError({
          cause: null,
          message: "Asset reminder not found for scheduled job. Skipping.",
          additionalData: { ...job.data },
          label: "Asset Scheduler",
          shouldBeCaptured: false,
        })
      );
      return;
    }

    /**
     * Stale-job guard: when the row tracks a DIFFERENT live job than the one
     * firing, this job was superseded (an edit whose cancel silently failed,
     * or a reconciliation re-arm) — firing it would double-notify or corrupt
     * the chain. A null reference is permissive (unknown state: fire).
     */
    if (
      reminder.activeSchedulerReference &&
      job.id &&
      reminder.activeSchedulerReference !== job.id
    ) {
      Logger.warn(
        new ShelfError({
          cause: null,
          message:
            "Skipping stale asset reminder job (superseded by a newer schedule).",
          additionalData: {
            ...job.data,
            jobId: job.id,
            activeSchedulerReference: reminder.activeSchedulerReference,
          },
          label: "Asset Scheduler",
          shouldBeCaptured: false,
        })
      );
      return;
    }

    /**
     * An archived asset is out of service: its reminders stay quiet, with no
     * email and no "System has sent" note. The reminder row is kept.
     *
     * A one-shot reminder fires as usual if the asset is reinstated before its
     * time. Clearing `activeSchedulerReference` records the skip: no job is
     * left to deliver this reminder, and the reminders list reads a past-due
     * reminder with no reference as "Not sent", whatever the asset's state
     * later. The write is conditioned on this job, so a reminder rescheduled
     * meanwhile keeps its new job.
     *
     * A recurring series instead advances silently to its next occurrence, so
     * it keeps running while the asset is archived and resumes notifying once
     * the asset is reinstated. Skipping without advancing would leave a dead
     * chain that boot reconciliation keeps re-arming.
     */
    if (reminder.asset.archivedAt) {
      if (isRecurringReminder(reminder)) {
        try {
          await advanceRecurringReminder({ reminder, now: new Date() });
        } catch (cause) {
          throw new RecurringAdvanceError(cause, reminder.id);
        }
        Logger.info(
          `Asset reminder ${reminder.id} occurrence skipped: asset ${reminder.assetId} is archived.`
        );
        return;
      }

      await db.assetReminder.updateMany({
        where: {
          id: reminder.id,
          organizationId: reminder.organizationId,
          activeSchedulerReference: job.id,
        },
        data: { activeSchedulerReference: null },
      });
      Logger.info(
        `Asset reminder ${reminder.id} skipped: asset ${reminder.assetId} is archived.`
      );
      return;
    }

    /**
     * Recurring series: advance the row to the next occurrence and schedule
     * the next job BEFORE notifying. If this critical step fails the error
     * escapes the wrapper as RecurringAdvanceError so pg-boss retries the
     * job — no email has gone out yet, so a retry cannot double-send.
     */
    const now = new Date();
    let nextOccurrence: Date | null = null;
    let seriesPaused = false;
    let seriesEnded = false;

    if (isRecurringReminder(reminder)) {
      const dueNow =
        reminder.alertDateTime.getTime() <=
        now.getTime() + ADVANCE_CLOCK_EPSILON_MS;

      try {
        if (dueNow) {
          // Normal fire: advance the row and schedule the next occurrence.
          const { next, paused, ended } = await advanceRecurringReminder({
            reminder,
            now,
          });
          nextOccurrence = next;
          seriesPaused = paused;
          seriesEnded = ended;
        } else {
          // The row already points at a FUTURE occurrence while this job is
          // firing. The stale-job guard above proved this job is still the
          // row's active job (or the reference is null), so we are NOT looking
          // at a concurrent edit — the advance committed on a prior attempt
          // but scheduling the next job did not durably succeed (transient
          // sendAfter failure). Re-arm it idempotently (the singletonKey
          // dedupes if the job already exists) so the series is not orphaned
          // until boot reconciliation.
          await scheduleAssetReminder({
            data: {
              reminderId: reminder.id,
              eventType: ASSETS_EVENT_TYPE_MAP.REMINDER,
            },
            when: reminder.alertDateTime,
            options: recurringReminderJobOptions(
              reminder.id,
              reminder.alertDateTime
            ),
          });
          nextOccurrence = reminder.alertDateTime;
        }
      } catch (cause) {
        throw new RecurringAdvanceError(cause, reminder.id);
      }
    }

    const usersToSendEmail = reminder.teamMembers
      .filter((tm) => !!tm.user)
      .map((teamMember) => teamMember.user! as UserToEmail);

    const hasTeamMemberWithoutUser = reminder.teamMembers.some(
      (tm) => !tm.user
    );

    /**
     * If there is some teamMember without a user associated
     * that means the access has been revoked to that teamMember.
     * Then, in this case we have to send an email to the owner with special note.
     */
    if (hasTeamMemberWithoutUser) {
      const owner = await db.user.findFirst({
        where: {
          userOrganizations: {
            some: {
              organizationId: reminder.organizationId,
              roles: {
                hasSome: rolesWhere((p) => p.membership.ownsWorkspace),
              },
            },
          },
        },
        select: {
          email: true,
          firstName: true,
          lastName: true,
          displayName: true,
        },
      });

      if (!owner) {
        throw new ShelfError({
          cause: null,
          message: "No owner found",
          label: "Asset Scheduler",
        });
      }

      usersToSendEmail.push({
        ...owner,
        isOwner: true,
      });
    }

    /**
     * Note text reflects the chain state so users can see why a series
     * continues, ended, or stopped, straight from the asset activity.
     */
    // Reminder names are user-supplied and render as literal text here.
    let noteContent = `**System** has sent **${stripMarkdocDelimiters(
      reminder.name
    )}** reminder.`;
    if (nextOccurrence) {
      noteContent += ` Next reminder scheduled for ${formatOccurrenceInZone(
        nextOccurrence,
        reminder.recurrenceTimezone
      )}.`;
    } else if (seriesEnded) {
      noteContent += ` This was the last occurrence of this recurring reminder (end date reached).`;
    } else if (seriesPaused) {
      noteContent += ` This recurring reminder was paused because the workspace plan no longer includes recurring reminders.`;
    }

    /** Sending alert mails to all associated users. */
    await Promise.all([
      ...usersToSendEmail.map(async (user) => {
        const html = await assetAlertEmailHtmlString({
          asset: reminder.asset,
          user,
          reminder,
          workspaceName: reminder.organization.name,
          isOwner: user.isOwner,
          customEmailFooter: reminder.organization.customEmailFooter,
          nextOccurrence,
        });

        sendEmail({
          subject: "⏰ Asset Reminder Notice - Shelf",
          to: user.email,
          text: assetAlertEmailText({
            asset: reminder.asset,
            user,
            reminder,
            workspaceName: reminder.organization.name,
            isOwner: user.isOwner,
            customEmailFooter: reminder.organization.customEmailFooter,
            nextOccurrence,
          }),
          html,
        });
      }),
      createNote({
        assetId: reminder.assetId,
        // why: scope the note's asset to the reminder's org so the
        // scheduled job cannot write a note onto a foreign-tenant asset
        // (defense-in-depth cross-org IDOR guard)
        organizationId: reminder.organizationId,
        userId: reminder.createdById,
        type: "UPDATE",
        content: noteContent,
      }),
    ]);
  },
};

/**
 * This function is used to register asset workers.
 * Workers are used to process scheduled events.
 *
 * On handler failure we log (last-retry only, mirroring the email worker's
 * noise control in `emails/email.worker.server.ts`) and **rethrow** so
 * pg-boss marks the job failed and retries it per the bounded `retryLimit`
 * set on enqueue in `scheduler.server.ts`. Swallowing the error would make
 * pg-boss mark the job COMPLETED and lose the reminder with no retry.
 *
 * @throws {ShelfError} Rethrows the wrapped cause after logging, so pg-boss
 * treats the job as failed and retries it.
 */
export async function regierAssetWorkers() {
  await scheduler.work<AssetsSchedulerData>(
    QueueNames.assetsQueue,
    // why: includeMetadata exposes job.retrycount/job.retrylimit on the job
    // object below, which we need to only log on the final retry attempt
    { includeMetadata: true },
    async (job) => {
      const handler = ASSET_SCHEDULER_EVENT_HANDLERS[job.data.eventType];

      try {
        await handler(job);
      } catch (cause) {
        // why: pg-boss increments retrycount at fetch time, so with N retries
        // the handler observes retrycount = 0, 1, 2, ... N — the final attempt
        // has retrycount === retrylimit. Using `- 1` here double-logs (fires on
        // both the second-to-last AND the final attempt).
        const isLastRetry =
          job.retrycount != null &&
          job.retrylimit != null &&
          job.retrycount >= job.retrylimit;

        if (isLastRetry) {
          Logger.error(
            new ShelfError({
              cause,
              message: "Something went wrong while executing scheduled work.",
              additionalData: {
                data: job.data,
                work: job.data.eventType,
                retryCount: job.retrycount,
                retryLimit: job.retrylimit,
              },
              label: "Asset Scheduler",
            })
          );
        }

        throw cause;
      }
    }
  );
}
